import { createHash } from "node:crypto";
import { readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { defineConfig, type Plugin } from "vite";
import react from "@vitejs/plugin-react";

/**
 * Offline support (PWA): after a production build, write sw.js with the list
 * of every emitted file plus public/ (3D models, icons). The service worker
 * caches them on install, serves them cache-first, and falls back to the
 * cached index.html for navigations, so the installed app works without a
 * network. Weather requests (other origins) always go to the network; the app
 * keeps its own weather cache. src/app/registerSw.ts registers it.
 */
function serviceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "solar-sim-service-worker",
    apply: "build",
    configResolved(c) {
      publicDir = c.publicDir;
    },
    generateBundle(_, bundle) {
      const files = new Set<string>(["./", "./index.html"]);
      for (const f of Object.keys(bundle)) if (!f.endsWith(".map")) files.add(`./${f}`);
      const walk = (dir: string): void => {
        for (const n of readdirSync(dir)) {
          const p = join(dir, n);
          if (statSync(p).isDirectory()) walk(p);
          else files.add(`./${relative(publicDir, p).split("\\").join("/")}`);
        }
      };
      if (publicDir) walk(publicDir);
      const list = [...files].sort();
      const version = createHash("sha256").update(list.join("\n")).digest("hex").slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: `// Generated by vite.config.ts (serviceWorker plugin). Do not edit.
const CACHE = "solar-sim-${version}";
const PRECACHE = ${JSON.stringify(list)};
self.addEventListener("install", (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});
self.addEventListener("activate", (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("solar-sim-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("fetch", (e) => {
  const req = e.request;
  if (req.method !== "GET" || new URL(req.url).origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    const shell = new URL("./index.html", self.registration.scope).href;
    e.respondWith(fetch(req).catch(() => caches.match(shell)));
    return;
  }
  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`,
      });
    },
  };
}

export default defineConfig({
  plugins: [react(), serviceWorker()],
  server: { port: 5173, strictPort: true },
  build: {
    target: "es2022",
    chunkSizeWarningLimit: 1500,
    rollupOptions: {
      output: {
        manualChunks(id) {
          if (id.includes("node_modules/three/")) return "three";
          if (id.includes("@react-three")) return "r3f";
          return undefined;
        },
      },
    },
  },
});
